#!/usr/bin/env python3
"""Hidden Grottoes: generate the engine table from gba/grottoes/grottoes.json and check placement.

    python3 tools/gba/grottoes/grottoes.py generate ENGINE   write the two generated engine files
    python3 tools/gba/grottoes/grottoes.py check ENGINE      validate the spec, entrances, and that
                                                             the generated files are current
    python3 tools/gba/grottoes/grottoes.py place ENGINE ID   add the entrance warp for grotto ID to
                                                             its map.json (art is the map's job)

ENGINE is a pokeemerald-expansion checkout on the `apocrypha` branch (or game/). Generated files:
include/constants/hidden_grottoes.h and src/data/hidden_grottoes.h. The mechanic itself is
src/hidden_grotto.c; the rules are in docs/HIDDEN_GROTTOES.md.
"""
from __future__ import annotations
import json, re, struct, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SPEC = ROOT / 'gba/grottoes/grottoes.json'
GROTTO_MAP = 'MAP_HIDDEN_GROTTO'
GENDERS = {'any': 'GROTTO_GENDER_ANY', 'male': 'GROTTO_GENDER_MALE', 'female': 'GROTTO_GENDER_FEMALE'}
# Behaviors that warp the player when stepped on (cave mouths, doors).
ENTRANCE_BEHAVIORS = {'MB_NON_ANIMATED_DOOR', 'MB_ANIMATED_DOOR', 'MB_DEEP_SOUTH_WARP', 'MB_WATER_DOOR',
                      'MB_PETALBURG_GYM_DOOR'}
HEADER = ('// Generated by pokemon-apocrypha tools/gba/grottoes/grottoes.py from gba/grottoes/grottoes.json.\n'
          '// Do not edit by hand: change the JSON and regenerate.\n')


def load_spec():
    return json.loads(SPEC.read_text())


class Engine:
    def __init__(self, path):
        self.root = Path(path)
        if not (self.root / 'include/constants/hidden_grotto.h').exists():
            sys.exit(f'{self.root}: not an engine checkout with the Hidden Grotto mechanic')
        self._maps = None
        self._species_src = None

    def text(self, rel):
        return (self.root / rel).read_text(errors='replace')

    def capacity(self):
        return int(re.search(r'#define HIDDEN_GROTTO_CAPACITY\s+(\d+)', self.text('include/constants/hidden_grotto.h')).group(1))

    def maps(self):
        if self._maps is None:
            self._maps = {}
            for p in (self.root / 'data/maps').glob('*/map.json'):
                try:
                    self._maps[json.loads(p.read_text())['id']] = p
                except (KeyError, json.JSONDecodeError):
                    pass
        return self._maps

    def items(self):
        return set(re.findall(r'^\s*(ITEM_\w+)\s*[,=]', self.text('include/constants/items.h'), re.M))

    def species(self):
        return set(re.findall(r'#define (SPECIES_\w+)\s', self.text('include/constants/species.h'))) | \
               set(re.findall(r'^\s*(SPECIES_\w+)\s*[,=]', self.text('include/constants/species.h'), re.M))

    def hidden_ability(self, species):
        """The species' third ability slot as the engine builds it (None if the species isn't built).

        Runs the host C preprocessor over src/pokemon.c so config switches (P_UPDATED_ABILITIES,
        roster families) and ability macros resolve exactly as in the ROM."""
        if self._species_src is None:
            with tempfile.TemporaryDirectory() as stub:
                (Path(stub) / 'constants').mkdir()
                (Path(stub) / 'constants/hidden_grottoes.h').write_text('#define HIDDEN_GROTTO_COUNT 0\n')
                out = Path(stub) / 'pokemon.i'
                r = subprocess.run(['gcc', '-E', '-iquote', 'include', '-idirafter', stub, '-Wno-trigraphs',
                                    '-DMODERN=1', '-DTESTING=0', '-DEMERALD', '-std=gnu17', 'src/pokemon.c', '-o', str(out)],
                                   cwd=self.root, capture_output=True, text=True)
                if r.returncode:
                    sys.exit('preprocessing src/pokemon.c failed:\n' + r.stderr[-2000:])
                self._species_src = out.read_text(errors='replace')
        m = re.search(r'\[\s*' + re.escape(species) + r'\s*\]\s*=\s*\{', self._species_src)
        if not m:
            return None
        a = re.search(r'\.abilities\s*=\s*\{([^}]*)\}', self._species_src[m.end():m.end() + 20000])
        parts = [x.strip() for x in a.group(1).split(',')] if a else []
        return parts[2] if len(parts) > 2 else 'ABILITY_NONE'

    def behavior_at(self, map_json, x, y):
        """Metatile behavior name at (x, y) of a map, or None if it can't be resolved."""
        m = json.loads(map_json.read_text())
        layouts = json.loads(self.text('data/layouts/layouts.json'))['layouts']
        lay = next((l for l in layouts if l.get('id') == m['layout']), None)
        if not lay:
            return None
        w, h = lay['width'], lay['height']
        if not (0 <= x < w and 0 <= y < h):
            return 'OUTSIDE'
        blocks = struct.unpack(f'<{w*h}H', (self.root / lay['blockdata_filepath']).read_bytes())
        mid = blocks[y * w + x] & 0x3FF
        name = lay['primary_tileset'] if mid < 512 else lay['secondary_tileset']
        index = mid if mid < 512 else mid - 512
        hdr = re.search(r'const struct Tileset ' + re.escape(name) + r'\s*=\s*\{(.*?)\};', self.text('src/data/tilesets/headers.h'), re.S)
        if not hdr:
            return None
        sym = re.search(r'\.metatileAttributes\s*=\s*(\w+)', hdr.group(1)).group(1)
        inc = re.search(re.escape(sym) + r'\[\]\s*=\s*INCBIN_U16\("([^"]+)"\)', self.text('src/data/tilesets/metatiles.h'))
        if not inc:
            return None
        attrs = (self.root / inc.group(1)).read_bytes()
        if index * 2 + 2 > len(attrs):
            return None
        value = struct.unpack_from('<H', attrs, index * 2)[0] & 0xFF
        names = re.findall(r'^\s*(MB_\w+)', self.text('include/constants/metatile_behaviors.h'), re.M)
        return names[value] if value < len(names) else None


def validate(spec, eng, check_entrances=True):
    errors = []
    cap = eng.capacity()
    maps, items, species = eng.maps(), eng.items(), eng.species()
    if GROTTO_MAP not in maps:
        errors.append(f'{GROTTO_MAP} is missing from the engine')
    ids, indexes = set(), set()
    for g in spec['grottoes']:
        tag = g.get('id', '?')
        if not re.fullmatch(r'GROTTO_[A-Z0-9_]+', tag):
            errors.append(f'{tag}: id must look like GROTTO_NAME')
        if tag in ids:
            errors.append(f'{tag}: duplicate id')
        ids.add(tag)
        i = g.get('index')
        if not isinstance(i, int) or not 0 <= i < cap:
            errors.append(f'{tag}: index must be 0..{cap - 1} (HIDDEN_GROTTO_CAPACITY)')
        elif i in indexes:
            errors.append(f'{tag}: index {i} already used; indexes are save slots and never move')
        indexes.add(i)
        if g.get('map') not in maps:
            errors.append(f'{tag}: unknown map {g.get("map")}')
        slots = g.get('slots', [])
        if not 1 <= len(slots) <= 254:
            errors.append(f'{tag}: needs 1..254 slots')
        for n, s in enumerate(slots):
            st = f'{tag} slot {n}'
            if not isinstance(s.get('weight'), int) or not 1 <= s['weight'] <= 255:
                errors.append(f'{st}: weight must be 1..255')
            if ('species' in s) == ('item' in s):
                errors.append(f'{st}: give exactly one of species or item')
            elif 'species' in s:
                sp = s['species']
                if sp not in species:
                    errors.append(f'{st}: unknown species {sp}')
                else:
                    ha = eng.hidden_ability(sp)
                    if ha is None:
                        errors.append(f'{st}: no species_info entry found for {sp}')
                    elif ha == 'ABILITY_NONE':
                        errors.append(f'{st}: {sp} has no Hidden Ability')
                lv = s.get('level')
                if not (isinstance(lv, list) and len(lv) == 2 and 1 <= lv[0] <= lv[1] <= 100):
                    errors.append(f'{st}: level must be [min, max] within 1..100')
                if s.get('gender', 'any') not in GENDERS:
                    errors.append(f'{st}: gender must be any, male or female')
            elif s['item'] not in items:
                errors.append(f'{st}: unknown item {s["item"]}')
        if check_entrances and g.get('map') in maps:
            errors += check_entrance(g, eng)
    return errors


def check_entrance(g, eng):
    errors, tag = [], g['id']
    path = eng.maps()[g['map']]
    warps = json.loads(path.read_text()).get('warp_events') or []
    hit = [w for w in warps if w['x'] == g['x'] and w['y'] == g['y']]
    if not hit:
        errors.append(f'{tag}: no warp on {g["map"]} at ({g["x"]},{g["y"]}); run "place"')
    elif hit[0]['dest_map'] != GROTTO_MAP or str(hit[0]['dest_warp_id']) != '0':
        errors.append(f'{tag}: the warp at ({g["x"]},{g["y"]}) must go to {GROTTO_MAP} warp 0')
    b = eng.behavior_at(path, g['x'], g['y'])
    if b is None:
        errors.append(f'{tag}: could not read the entrance metatile behavior')
    elif b not in ENTRANCE_BEHAVIORS:
        errors.append(f'{tag}: entrance tile behavior is {b}; it must warp when stepped on ({", ".join(sorted(ENTRANCE_BEHAVIORS))})')
    return errors


def render(spec):
    gs = sorted(spec['grottoes'], key=lambda g: g['index'])
    count = (gs[-1]['index'] + 1) if gs else 0
    consts = HEADER + '#ifndef GUARD_CONSTANTS_HIDDEN_GROTTOES_H\n#define GUARD_CONSTANTS_HIDDEN_GROTTOES_H\n\n'
    for g in gs:
        consts += f'#define {g["id"]:<40} {g["index"]}  // {g["name"]}\n'
    consts += f'\n#define HIDDEN_GROTTO_COUNT {count}\n\n#endif // GUARD_CONSTANTS_HIDDEN_GROTTOES_H\n'

    data = HEADER + '\n'
    for g in gs:
        name = 's' + ''.join(p.capitalize() for p in g['id'].lower().split('_')) + 'Slots'
        g['_slots'] = name
        data += f'static const struct HiddenGrottoSlot {name}[] =\n{{\n'
        for s in g['slots']:
            if 'species' in s:
                data += (f'    {{ .species = {s["species"]}, .item = ITEM_NONE, .minLevel = {s["level"][0]}, '
                         f'.maxLevel = {s["level"][1]}, .gender = {GENDERS[s.get("gender", "any")]}, .weight = {s["weight"]} }},\n')
            else:
                data += f'    {{ .species = SPECIES_NONE, .item = {s["item"]}, .weight = {s["weight"]} }},\n'
        data += '};\n\n'
    data += 'const struct HiddenGrotto gHiddenGrottoes[HIDDEN_GROTTO_COUNT + 1] =\n{\n'
    for g in gs:
        data += (f'    [{g["id"]}] =\n    {{\n        .map = {g["map"]},\n        .x = {g["x"]},\n        .y = {g["y"]},\n'
                 f'        .slotCount = ARRAY_COUNT({g["_slots"]}),\n        .slots = {g["_slots"]},\n    }},\n')
    data += '};\n'
    return consts, data


OUT = ('include/constants/hidden_grottoes.h', 'src/data/hidden_grottoes.h')


def main(argv):
    if len(argv) < 3 or argv[1] not in ('generate', 'check', 'place'):
        print(__doc__); return 2
    spec, eng = load_spec(), Engine(argv[2])
    if argv[1] == 'place':
        g = next((g for g in spec['grottoes'] if g['id'] == argv[3]), None) if len(argv) > 3 else None
        if not g:
            sys.exit('place ENGINE GROTTO_ID: unknown grotto id')
        path = eng.maps()[g['map']]
        m = json.loads(path.read_text())
        warps = m.get('warp_events') or []
        if any(w['x'] == g['x'] and w['y'] == g['y'] for w in warps):
            print(f'{g["map"]} already has a warp at ({g["x"]},{g["y"]})')
        else:
            warps.append({'x': g['x'], 'y': g['y'], 'elevation': 0, 'dest_map': GROTTO_MAP, 'dest_warp_id': '0'})
            m['warp_events'] = warps
            path.write_text(json.dumps(m, indent=2, ensure_ascii=False) + '\n')
            print(f'added the grotto warp to {path}')
        b = eng.behavior_at(path, g['x'], g['y'])
        if b not in ENTRANCE_BEHAVIORS:
            print(f'note: the entrance tile is {b}; draw an entrance metatile whose behavior warps when stepped on')
        return 0
    errors = validate(spec, eng, check_entrances=(argv[1] == 'check'))
    if errors:
        print('\n'.join('ERROR ' + e for e in errors)); return 1
    consts, data = render(spec)
    if argv[1] == 'generate':
        for rel, text in zip(OUT, (consts, data)):
            (eng.root / rel).write_text(text)
            print('wrote', eng.root / rel)
        return 0
    stale = [rel for rel, text in zip(OUT, (consts, data)) if not (eng.root / rel).exists() or (eng.root / rel).read_text() != text]
    if stale:
        print('ERROR generated files are out of date, run generate: ' + ', '.join(stale)); return 1
    print(f'ok: {len(spec["grottoes"])} grottoes, entrances and generated files current')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
