"""Headless mGBA checks for the decoded-HGSS Route 29 rebuild (each phase a fresh emulator process).

  write  new game; Cherrygrove -> Route 29 across the west connection and back; the full route along the
         path to the New Bark connection; every HGSS ledge row (jump down, blocked from below); both ledge
         walls; the closed Route 46 gate; the carried lookout railing; tall grass with an empty party starts
         no battle; both signs; the cuttable trees and the Apricorn tree block; the hidden Potion (found once);
         camera views for review; ordinary save at the lookout
  read   cold flash reload of that save
  menu   title screen -> Continue from a cold boot

    MGBA_FLAGS='-I... -L... -lmgba ...' python3 tools/gba/maps/route29_hgss/runtime.py ENGINE_DIR OUT_DIR [write read menu]

Probe cells are checked against the generator's traversal grid before the emulator runs, so a probe never
starts on a blocked cell by mistake.
"""
