SHOTS = [('view-west-lawn', 18, 12), ('view-upper-lawn', 24, 9), ('view-west-path', 16, 22), ('view-centre', 40, 21), ('view-gate', 52, 12),
         ('view-south-ledges', 56, 26), ('view-east-grass', 70, 20), ('view-east-path', 90, 18), ('view-ridge', 40, 38), ('view-lookout', 58, 31)]


def grids():
    mat = (EVID / 'source/material-grid.txt').read_text().splitlines()
    trav = (EVID / 'source/traversal-grid.txt').read_text().splitlines()
    return mat, trav


def probes():
    """Derive the probe cells from the decoded grids (map coordinates) and check every start cell is open."""
    mat, trav = grids(); HH, HW = len(mat), len(mat[0])
    def M(x, y): hx, hz = x - COL0, y - ROW0; return mat[hz][hx] if 0 <= hz < HH and 0 <= hx < HW else '?'
    def open_(x, y): hx, hz = x - COL0, y - ROW0; return 0 <= hz < HH and 0 <= hx < HW and trav[hz][hx] != 'X' and mat[hz][hx] not in 'G_'
    ledges, walls = [], []
    for hz in range(HH):
        run = []
        for hx in range(HW + 1):
            if hx < HW and mat[hz][hx] == '_': run.append(hx)
            elif run:
                mid = run[len(run) // 2]; x, y = mid + COL0, hz + ROW0
                if open_(x, y - 1) and M(x, y + 1) in '.PG': ledges.append((x, y, f'ledge-{x}-{y}'))
                run = []
    for hz in range(HH):
        for hx in range(HW):
            if mat[hz][hx] in '|!':
                x, y = hx + COL0, hz + ROW0
                if mat[hz][hx - 1] == 'P' and open_(x + 1, y): walls.append((x + 1, y, LEFT, f'wall-{x}-{y}-from-east'))
                elif open_(x - 1, y): walls.append((x - 1, y, RIGHT, f'wall-{x}-{y}-from-west'))
    walls = [w for i, w in enumerate(walls) if i % 3 == 0]                 # one probe per three rows of each wall is plenty
    return ledges, walls, M, open_


def generate(game):
    ledges, walls, M, open_ = probes()
    tb = (game / 'data/layouts/CherrygroveCity/map.bin').read_bytes()
    tw = 80; th = len(tb) // 2 // tw
    town = struct.unpack('<%dH' % (tw * th), tb)
    east_rows = [y for y in range(th) if not (town[y * tw + tw - 1] >> 10) & 3]
    town_east_y = east_rows[len(east_rows) // 2]
    mj = json.loads((game / 'data/maps/CherrygroveRoute29Approach/map.json').read_text())
    signs = sorted((b['x'], b['y']) for b in mj['bg_events'] if b['type'] == 'sign')
    trees = [(o['x'], o['y']) for o in mj['object_events'] if o['graphics_id'] == 'OBJ_EVENT_GFX_CUTTABLE_TREE']
    events = json.loads((EVID / 'source/hgss-events.json').read_text())
    apricorn = next((o['hx'] + COL0, o['hz'] + ROW0) for o in events['objects'] if o['id'] == 'obj_R29_bonguri')
    door = sorted((hx + COL0, hz + ROW0) for hz, row in enumerate(grids()[0]) for hx, ch in enumerate(row) if ch == 'D')
    grass = next((hx + COL0, hz + ROW0) for hz, row in enumerate(grids()[0]) for hx in range(len(row) - 7) if row[hx:hx + 7] == 'G' * 7)
    east_y = next(y for y in range(16, 24) if M(90, y) == 'P' and M(90, y + 1) == 'P')
    for x, y, _ in ledges: assert open_(x, y - 1), (x, y)
    for x, y, _, _ in walls: assert open_(x, y), (x, y)
    walk = [(2, town_east_y)] + [(x, 21) for x in (12, 18, 24)] + [(x, 23) for x in (30, 40, 50, 60)] + [(70, 26), (78, 26), (84, 18)]
    rep = dict(TOWN_EAST_X=tw - 1, TOWN_EAST_Y=town_east_y, EAST_Y=east_y, POTION_X=POTION[0], POTION_Y=POTION[1], SAVE_X=SAVE_AT[0], SAVE_Y=SAVE_AT[1],
               HIDDEN_FLAG=HIDDEN_FLAG, GATE_X=door[0][0], GATE_Y=door[0][1], GRASS_X=grass[0] - 1, GRASS_Y=grass[1],
               WEST_SIGN_X=signs[0][0], WEST_SIGN_Y=signs[0][1], EAST_SIGN_X=signs[-1][0], EAST_SIGN_Y=signs[-1][1],
               TOWN=TOWN, R29=R29, NEWBARK=NEWBARK, RIGHT=RIGHT, LEFT=LEFT, UP=UP, DOWN=DOWN)
    src = TEMPLATE.replace('RUNTIME_C', str(ROOT / 'tools/gba/maps/runtime.c'))
    src = src.replace('WALK', ''.join(f'go(R29,{x},{y});shot("walk-{i:02d}-{x}-{y}");' for i, (x, y) in enumerate(walk)))
    src = src.replace('LEDGES', ''.join(f'ledge({x},{y},"{t}");' for x, y, t in ledges))
    src = src.replace('WALLS', ''.join(f'blocked({x},{y},{k},"{t}");' for x, y, k, t in walls))
    src = src.replace('TREES', ''.join(f'blocked({x},{y + 1},UP,"cut-tree-{x}-{y}");shot("cut-tree-{x}-{y}");' for x, y in trees)
                      + f'blocked({apricorn[0]},{apricorn[1] + 1},UP,"apricorn-tree");shot("apricorn-tree");')
    src = src.replace('SHOTS', ''.join(f'go(R29,{x},{y});shot("{t}");' for t, x, y in SHOTS))
    defines = ''.join(f'#define {k} {v}\n' for k, v in rep.items()) + '#define A 1\n#define B 2\n'
    src = src.replace('#undef main\n', '#undef main\n' + defines, 1)
    return src, dict(town_east=(tw - 1, town_east_y), east_y=east_y, ledges=ledges, walls=[w[:2] + (w[3],) for w in walls], trees=trees, apricorn=apricorn, gate_door=door, signs=signs)


def main():
    game = Path(sys.argv[1]).resolve(); out = Path(sys.argv[2]).resolve()
    if out.exists(): shutil.rmtree(out)
    out.mkdir(parents=True)
    src, plan = generate(game); csrc = out / 'route29_runtime.c'; csrc.write_text(src)
    (out / 'plan.json').write_text(json.dumps(plan, indent=2) + '\n')
    flags = shlex.split(os.environ.get('MGBA_FLAGS', '')) or ['-lmgba']
    subprocess.run(['cc', '-O1', str(csrc), *flags, '-o', str(out / 'runtime')], check=True)
    nm = shutil.which('arm-none-eabi-nm') or str(ROOT / 'tools/vendor/gba/arm-gnu-toolchain-14.2.rel1-x86_64-arm-none-eabi/bin/arm-none-eabi-nm')
    lines = subprocess.check_output([nm, str(game / 'pokeemerald.elf')], text=True)
    wanted = {'MapProof_Boot', 'MapProof_Enter', 'MapProof_ReadState', 'MapProof_Resume', 'gMapProofState', 'TrySavingData', 'LoadGameSave',
              'ArePlayerFieldControlsLocked', 'FlagGet', 'CalculatePlayerPartyCount', 'gMain', 'CB2_Overworld', 'gSaveBlock2Ptr'}
    symbols = {r[2]: r[0] for l in lines.splitlines() if len(r := l.split()) == 3 and r[2] in wanted}; assert symbols.keys() == wanted, wanted - symbols.keys()
    (out / 'symbols.txt').write_text(''.join(f'{k} {v}\n' for k, v in symbols.items()))
    results = []
    for phase in (sys.argv[3:] or ['write', 'read', 'menu']):
        r = subprocess.run([str(out / 'runtime'), str(game / 'pokeemerald.gba'), str(out / 'symbols.txt'), str(out), phase], capture_output=True, text=True, timeout=3600)
        (out / (phase + '.jsonl')).write_text(r.stdout)
        results.append(dict(phase=phase, exit_code=r.returncode, stderr=r.stderr, observations=[json.loads(l) for l in r.stdout.splitlines() if l.startswith('{')]))
        (out / 'results.json').write_text(json.dumps(results, indent=2) + '\n')
        for file in out.glob('*.ppm'):
            Image.open(file).save(file.with_suffix('.png')); file.unlink()
        print(phase, r.returncode, r.stderr[-600:], flush=True)
        if r.returncode != 0: sys.exit(r.returncode)
    print('All phases passed.')


if __name__ == '__main__':
    main()
