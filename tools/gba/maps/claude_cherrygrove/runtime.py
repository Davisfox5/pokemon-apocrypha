def generate():
    doors = [b for b in L.BUILDINGS]
    order = ['PlayerHouse', 'GoldHouse', 'NeighborHouse', 'TransplantHouse', 'Mart', 'PokemonCenter']
    by = {b['name']: b for b in doors}
    door_cells = [L.door_of(by[n]) for n in order]
    views = [(50, 18), (40, 9), (44, 14), (43, 25), (24, 20), (19, 27), (21, 9)]
    shots = [('home-street', 50, 18), ('shops', 40, 9), ('gold-yard', 44, 14), ('park', 43, 25), ('beach', 24, 20), ('pier', 21, 26), ('lookout', 19, 6), ('cliff', 10, 5)]
    gid = {'OBJ_EVENT_GFX_JOHTO_GOLD': 1029, 'OBJ_EVENT_GFX_JOHTO_SILVER': 1030, 'OBJ_EVENT_GFX_JOHTO_KESTRA': 1031,
           'OBJ_EVENT_GFX_REGIONAL_HOENN': 1032, 'OBJ_EVENT_GFX_REGIONAL_KANTO': 1033, 'OBJ_EVENT_GFX_REGIONAL_JOHTO': 1034,
           'OBJ_EVENT_GFX_REGIONAL_SINNOH': 1035, 'OBJ_EVENT_GFX_REGIONAL_UNOVA': 1036,
           'OBJ_EVENT_GFX_JOHTO_BOY': 1024, 'OBJ_EVENT_GFX_JOHTO_GIRL': 1025, 'OBJ_EVENT_GFX_JOHTO_MAN': 1026, 'OBJ_EVENT_GFX_JOHTO_WOMAN': 1027}
    inter = []
    for npc in cast.NPCS:
        x, y = npc['pos']; key = 64  # face up towards the NPC one cell above
        inter.append(f'  interaction({gid[npc["gfx"]]},{x},{y + 1},64,"{npc["id"].lower()}-dialogue");')
    src = TEMPLATE
    src = src.replace('RUNTIME_C', str(ROOT / 'tools/gba/maps/runtime.c'))
    src = src.replace('SPAWN_X', str(L.SPAWN[0])).replace('SPAWN_Y', str(L.SPAWN[1]))
    src = src.replace('NDOORS', str(len(order))).replace('DOORS', ','.join(f'{{{x},{y}}}' for x, y in door_cells))
    src = src.replace('DOOR_MAPS', ','.join(str(MAP_INDEX[n]) for n in order))
    src = src.replace('EXITS', ','.join(f'{{{EXITS[n][0]},{EXITS[n][1]}}}' for n in order))
    src = src.replace('EAST_X', str(L.W - 1)).replace('EAST_Y', str(L.EAST_EXIT[0] + 1))
    src = src.replace('NORTH_X', str(L.NORTH_EXIT[0] + 1)).replace('NORTH_Y', '1')
    shore_y = 14; src = src.replace('SHORE_MIN', str(L.shore(shore_y))).replace('SHORE_X', str(L.shore(shore_y) + 2)).replace('SHORE_Y', str(shore_y))
    src = src.replace('NVIEWS', str(len(views))).replace('VIEWS', ','.join(f'{{{x},{y}}}' for x, y in views))
    src = src.replace('INTERACTIONS', '\n'.join(inter))
    src = src.replace('SHOTS', '\n'.join(f'  go(0,{x},{y});screenshot(argv[3],"{tag}");' for tag, x, y in shots))
    return src, views, shots

def main():
    game = Path(sys.argv[1]).resolve(); out = Path(sys.argv[2]).resolve(); out.mkdir(parents=True, exist_ok=False)
    src, views, shots = generate(); csrc = out / 'town_runtime.c'; csrc.write_text(src)
    (HERE / 'generated').mkdir(exist_ok=True); (HERE / 'generated' / 'town_runtime.c').write_text(src)
    flags = shlex.split(os.environ.get('MGBA_FLAGS', ''))
    if not flags and Path('/opt/homebrew/opt/mgba').exists(): flags = ['-I/opt/homebrew/opt/mgba/include', '-L/opt/homebrew/opt/mgba/lib', '-lmgba']
    if not flags: flags = ['-lmgba']
    subprocess.run(['cc', str(csrc), *flags, '-o', str(out / 'runtime')], check=True)
    lines = subprocess.check_output([str(TOOLCHAIN / 'bin/arm-none-eabi-nm'), str(game / 'pokeemerald.elf')], text=True)
    wanted = {'MapProof_Boot', 'MapProof_Enter', 'MapProof_ReadState', 'MapProof_Resume', 'gMapProofState', 'TrySavingData', 'LoadGameSave', 'ArePlayerFieldControlsLocked', 'gObjectEvents', 'gSprites'}
    symbols = {r[2]: r[0] for l in lines.splitlines() if len(r := l.split()) == 3 and r[2] in wanted}; assert symbols.keys() == wanted, wanted - symbols.keys()
    (out / 'symbols.txt').write_text(''.join(f'{k} {v}\n' for k, v in symbols.items()))
    results = []
    phases = sys.argv[3:] or ['write', 'read', 'menu', 'walk']
    for phase in phases:
        r = subprocess.run([str(out / 'runtime'), str(game / 'pokeemerald.gba'), str(out / 'symbols.txt'), str(out), phase], capture_output=True, text=True, timeout=900)
        (out / (phase + '.jsonl')).write_text(r.stdout)
        results.append(dict(phase=phase, exit_code=r.returncode, stderr=r.stderr, observations=[json.loads(l) for l in r.stdout.splitlines() if l.startswith('{') and 'objects' not in l]))
        (out / 'results.json').write_text(json.dumps(results, indent=2) + '\n')
        for file in out.glob('*.ppm'):
            Image.open(file).save(file.with_suffix('.png')); file.unlink()
        print(phase, r.returncode, r.stderr[-400:], flush=True)
        if r.returncode != 0: sys.exit(r.returncode)
    print('All phases passed.')

if __name__ == '__main__':
    main()
