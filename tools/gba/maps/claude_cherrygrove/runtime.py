#!/usr/bin/env python3
"""Generate and run the headless mGBA acceptance checks for the Claude Cherrygrove build.

Phases (each a fresh emulator process):
  write  new game at the front door, every door in and out, bedroom stairs, both
         route connections and back, shoreline collision, Mart menu, ordinary save
  read   cold flash reload of that save, ordinary LoadGameSave
  menu   real title screen -> Continue from a cold boot
  walk   NPC observation: 5 camera views x 360 samples of every resident, actual
         OBJ VRAM frames compared with the source cells, one conversation per cast
         member and visitor (stop, face player, resume)

    python3 tools/gba/maps/claude_cherrygrove/runtime.py tools/vendor/gba/claude-cherrygrove tools/vendor/gba/claude-check-NN
"""
