def patch_sinnoh_block(man, outdoor, enc_banks):
    path = os.path.join(HG, "src/data/map_headers.h")
    src = open(path).read()
    for h, m in man["maps"].items():
        cname = m["name"]
        i = src.find("[" + cname + "]")
        assert i > 0, cname
        j = src.find("}", i)
        seg = src[i:j]
        def setf(seg, field, val):
            return re.sub(r"(\." + field + r"\s*=\s*)[^,\n]+", r"\g<1>" + val, seg)
        seg = setf(seg, "scriptsBank", "NARC_scr_seq_scr_seq_0967_APOCSIN_bin")
        seg = setf(seg, "msgBank", "NARC_msg_msg_0830_APOCSIN_bin")
        if h in outdoor:
            fn = outdoor[h][0].replace(".json", "")
            seg = setf(seg, "eventsBank", f"NARC_zone_event_{fn}_bin")
        if h in enc_banks:
            seg = setf(seg, "wildEncounterBank", str(enc_banks[h]))
        src = src[:i] + seg + src[j:]
    open(path, "w").write(src)


def interior_header_entry(info, donor_entry):
    """Clone the donor header entry text with our events bank + mapsec."""
    seg = donor_entry
    def setf(seg, field, val):
        return re.sub(r"(\." + field + r"\s*=\s*)[^,\n]+", r"\g<1>" + val, seg)
    seg = setf(seg, "eventsBank", f"NARC_zone_event_{info['zefile']}_bin")
    seg = setf(seg, "mapsec", "MAPSEC_MYSTERY_ZONE")
    seg = setf(seg, "outgoingCalls", "FALSE")
    seg = setf(seg, "incomingCalls", "FALSE")
    seg = setf(seg, "radioSignal", "FALSE")
    return f"    [{info['cname']}] = " + seg + ","


def patch_interior_headers(interiors, interior_files):
    hdr_path = os.path.join(HG, "src/data/map_headers.h")
    src = open(hdr_path).read()
    donors = {}
    for kind, donor in (("PC", PC_DONOR_HDR), ("MART", MART_DONOR_HDR)):
        i = src.find("[" + donor + "]")
        j = src.find("},", i)
        donors[kind] = src[src.find("{", i):j + 1]
    entries = [MARK_BEGIN]
    for key, info in interiors.items():
        info["zefile"] = interior_files[key][0].replace(".json", "")
        entries.append(interior_header_entry(info, donors[info["kind"]]))
    entries.append(MARK_END)
    block = "\n".join(entries)
    if MARK_BEGIN in src:
        pre = src[:src.find(MARK_BEGIN)]
        post = src[src.find(MARK_END) + len(MARK_END):]
        src = pre + block + post
    else:
        # insert before the closing of the header array: after HOENN END block
        anchor = "// APOC_REGIONPORT HOENN END"
        i = src.find(anchor)
        assert i > 0
        i += len(anchor)
        src = src[:i] + "\n" + block + src[i:]
    open(hdr_path, "w").write(src)

    maps_path = os.path.join(HG, "include/constants/maps.h")
    src = open(maps_path).read()
    defines = [MARK_BEGIN]
    for key, info in interiors.items():
        defines.append(f"#define {info['cname']:<49} {info['id']}")
    defines.append(MARK_END)
    block = "\n".join(defines)
    if MARK_BEGIN in src:
        pre = src[:src.find(MARK_BEGIN)]
        post = src[src.find(MARK_END) + len(MARK_END):]
        src = pre + block + post
    else:
        anchor = "// APOC_REGIONPORT HOENN END"
        i = src.find(anchor)
        assert i > 0
        i += len(anchor)
        src = src[:i] + "\n\n" + block + src[i:]
    open(maps_path, "w").write(src)


