    with open(os.path.join(HG, "files/fielddata/script/scr_seq/scr_seq_0967_APOCSIN.s"), "w") as f:
        f.write("\n".join(s) + "\n")
    sign_scripts = {h: nscripts_before_signs + i + 1 for h, i in sign_map.items()}
    return sign_scripts, PORTER_SCRIPT + 1


