def enc_row(cols, label, enc):
    row = {}
    for c in cols:
        row[c] = "SPECIES_NONE" if "species" in c or c in (
            "hoenn1", "hoenn2", "sinnoh1", "sinnoh2") or c.startswith("swarm") else "0"
    row["mapname"] = label
    land = enc.get("land_encounters") or []
    if len(land) == 12:
        row["rate_walk"] = str(enc.get("land_rate", 0))
        for i, e in enumerate(land):
            row[f"land_lvl{i}"] = str(e["level"])
            for tod in ("morn", "day", "nite"):
                row[f"land_species_{tod}{i}"] = e["species"]
        morning, night = enc.get("morning") or [], enc.get("night") or []
        for j, sp in enumerate(morning[:2]):
            row[f"land_species_morn{j + 2}"] = sp
        for j, sp in enumerate(night[:2]):
            row[f"land_species_nite{j + 2}"] = sp
        ruby, sapp = enc.get("ruby") or [], enc.get("sapphire") or []
        if ruby:
            row["hoenn1"] = ruby[0]
        if sapp:
            row["hoenn2"] = sapp[0]
        radar = enc.get("radar") or []
        if len(radar) >= 2:
            row["sinnoh1"], row["sinnoh2"] = radar[0], radar[1]
        swarms = enc.get("swarms") or []
        if len(swarms) >= 2:
            row["swarm_species0"], row["swarm_species1"] = swarms[0], swarms[1]
            row["swarm_species2"] = row["swarm_species3"] = land[0]["species"]
    for kind, csvk in (("surf", "surf"), ("old_rod", "oldrod"),
                       ("good_rod", "goodrod"), ("super_rod", "superrod")):
        slots = enc.get(f"{kind}_encounters") or []
        rate = enc.get(f"{kind}_rate", 0)
        if slots:
            row[f"rate_{csvk}"] = str(rate)
            for i, e in enumerate(slots[:5]):
                row[f"lvl_min_{csvk}{i}"] = str(e["level_min"])
                row[f"lvl_max_{csvk}{i}"] = str(e["level_max"])
                row[f"species_{csvk}{i}"] = e["species"]
    return row


def append_encounters(man, plat):
    """Append one row per Sinnoh map with encounter data to BOTH csvs.
    Returns {header_name: bank_index}."""
    banks = {}
    for game in ("g", "s"):
        path = os.path.join(HG, f"files/fielddata/encountdata/{game}_enc_data.csv")
        lines = [l.rstrip("\n") for l in open(path)]
        cols = lines[0].split(",")
        kept = [l for l in lines[1:] if l.strip() and not l.startswith("APOCSIN_")]
        rows = []
        for h, info in plat.items():
            if not info["enc"]:
                continue
            label = "APOCSIN_" + man["maps"][h]["name"].replace("MAP_APOC_SINNOH_", "")
            r = enc_row(cols, label, info["enc"])
            if r["rate_walk"] == "0" and r["rate_surf"] == "0":
                continue
            rows.append((h, ",".join(r[c] for c in cols)))
        for i, (h, _) in enumerate(rows):
            banks[h] = len(kept) + i
        with open(path, "w") as f:
            f.write("\n".join([lines[0]] + kept + [r for _, r in rows]) + "\n")
    return banks


