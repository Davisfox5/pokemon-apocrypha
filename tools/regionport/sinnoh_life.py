def line_index_for(sprite, is_trainer, is_city, salt):
    cats = ["any"]
    if is_trainer:
        cats = ["trainer", "any"]
    elif sprite in KID_SPRITES:
        cats = ["kid", "any"]
    elif sprite in ELDER_SPRITES:
        cats = ["elder", "any"]
    elif sprite in WATER_SPRITES:
        cats = ["water", "any"]
    elif is_city:
        cats = ["city", "any"]
    else:
        cats = ["route", "any"]
    idxs = [i for i, (c, _) in enumerate(LINES) if c in cats]
    return idxs[salt % len(idxs)]


DIRS = {"NORTH": 0, "SOUTH": 1, "WEST": 2, "EAST": 3, "LEFT": 2, "RIGHT": 3}


def convert_movement(o):
    """Platinum object -> (movement, facing, xRange, yRange) or None to skip."""
    mt = o["movement_type"].replace("MOVEMENT_TYPE_", "")
    rx = max(int(o.get("movement_range_x", 1)), 1)
    rz = max(int(o.get("movement_range_z", 1)), 1)
    facing = int(o.get("initial_dir", 0)) & 3
    if mt in ("BERRY_SOIL", "FOLLOW_PARTNER_TRAINER") or mt.startswith("DISGUISE"):
        return None
    if mt == "WANDER_AROUND":
        return 3, facing, rx, rz
    if mt == "WANDER_WEST_AND_EAST":
        return 5, facing, rx, 0
    if mt == "WANDER_NORTH_AND_SOUTH":
        return 4, facing, 0, rz
    if mt == "WALK_BACK_AND_FORTH":
        return (5, facing, rx, 0) if rx >= rz else (4, facing, 0, rz)
    if mt.startswith("WALK_") or mt.startswith("ROTATE") or mt == "LOOK_AROUND":
        return 2, facing, 0, 0
    if mt == "NONE":
        return 0, facing, 0, 0
    if mt.startswith("LOOK_"):
        parts = mt[5:].split("_AND_")[0].split("_")
        d = DIRS.get(parts[0], facing)
        return 0, d, 0, 0
    return 0, facing, 0, 0


def map_sprite(gfx):
    name = gfx.replace("OBJ_EVENT_GFX_", "")
    for s in SKIP_GFX_SUBSTR:
        if s in name:
            return None
    if name in SPRITE_MAP:
        return SPRITE_MAP[name]
    # heuristic: unknown people get a stable generic sprite
    return FALLBACK_SPRITES[hash(name) % len(FALLBACK_SPRITES)]


def parse_plat_header_field(hdrs, h, name):
    i = hdrs.find("[" + h + "]")
    seg = hdrs[i:hdrs.find("}", i)]
    m = re.search(r"\." + name + r"\s*=\s*([^,\n]+)", seg)
    return m.group(1).strip() if m else None


def load_platinum(man):
    hdrs = open(os.path.join(PLAT, "include/data/map_headers.h")).read()
    order = [l.strip() for l in open(os.path.join(PLAT, "res/field/events/zone_event.order")) if l.strip()]
    encorder = [l.strip().replace(".bin", "") for l in
                open(os.path.join(PLAT, "res/field/encounters/encounters.order")) if l.strip()]
    plat = {}
    for h in man["maps"]:
        ev = parse_plat_header_field(hdrs, h, "eventsArchiveID")
        evfile = order[int(ev, 0)] if re.match(r"^(0x)?\d+$", ev) else ev
        events = json.load(open(os.path.join(PLAT, "res/field/events", evfile + ".json")))
        enc = parse_plat_header_field(hdrs, h, "wildEncountersArchiveID")
        encounters = None
        if enc is not None:
            if re.match(r"^(0x[0-9a-fA-F]+|\d+)$", enc):
                e = int(enc, 0)
                encfile = encorder[e] if e != 0xFFFF and e < len(encorder) else None
            else:
                encfile = enc
            if encfile:
                encounters = json.load(open(os.path.join(PLAT, "res/field/encounters", encfile + ".json")))
        mtype = parse_plat_header_field(hdrs, h, "mapType")
        plat[h] = {"events": events, "enc": encounters, "is_city": mtype == "0x1"}
    return plat


