def build_interior_events(interiors, outdoor, man):
    """Clone donor events; retarget the exit warp; drop other warps."""
    donors = {"PC": json.load(open(os.path.join(ZE_DIR, PC_DONOR_EVENTS))),
              "MART": json.load(open(os.path.join(ZE_DIR, MART_DONOR_EVENTS)))}
    files = {}
    for i, (key, info) in enumerate(interiors.items()):
        d = json.loads(json.dumps(donors[info["kind"]]))  # deep copy
        city_h = info["city"]
        city_cname = man["maps"][city_h]["name"]
        anchor = 0
        if city_h in outdoor:
            anchor = outdoor[city_h][2].get(key, 0)
        warps = [w for w in d.get("warps", []) if w["header"] == "MAP_CHERRYGROVE"]
        assert warps, f"donor {info['kind']} has no exit warp"
        for w in warps:
            w["header"] = city_cname
            w["anchor"] = anchor
        d["warps"] = warps
        suffix = info["cname"].replace("MAP_APOC_SIN_", "")
        fn = f"{INTERIOR_ZE_BASE + i}_APOCSIN_{suffix}.json"
        files[key] = (fn, d)
    return files


